package install

import (
	"fmt"
	"os/exec"
	"strings"

	"github.com/k18k/entrypoint/gateway/internal/config"
)

// FirewallUnit loads the per-IP limits into the kernel at boot and removes them when stopped.
const FirewallUnit = "entrypoint-firewall.service"

// FirewallRules renders the nftables table with the per-IP limits on the public side. It lives in
// its own table, so it only drops what goes over a limit and never touches other rules. IPv6
// clients are counted per /64, the smallest block one user usually gets.
func FirewallRules(cfg config.Config) string {
	l := cfg.Limits
	var b strings.Builder
	b.WriteString("# Generated by entrypoint install; changes are overwritten.\n")
	b.WriteString("table inet entrypoint\ndelete table inet entrypoint\ntable inet entrypoint {\n")
	b.WriteString("\tset conn4 { type ipv4_addr; flags dynamic; }\n\tset conn6 { type ipv6_addr; flags dynamic; }\n")
	b.WriteString("\tset rate4 { type ipv4_addr; flags dynamic; timeout 1m; }\n\tset rate6 { type ipv6_addr; flags dynamic; timeout 1m; }\n")
	b.WriteString("\tchain input {\n\t\ttype filter hook input priority filter - 5; policy accept;\n")
	if n := l.PerIPNewConnsPerSecond; n > 0 {
		for _, src := range []string{"@rate4 { ip saddr", "@rate6 { ip6 saddr & ffff:ffff:ffff:ffff::"} {
			fmt.Fprintf(&b, "\t\ttcp dport { 80, 443, %d } ct state new add %s limit rate over %d/second burst %d packets } counter drop\n", cfg.TunnelPort, src, n, 2*n)
		}
	}
	if n := l.PerIPConnections; n > 0 {
		for _, src := range []string{"@conn4 { ip saddr", "@conn6 { ip6 saddr & ffff:ffff:ffff:ffff::"} {
			fmt.Fprintf(&b, "\t\ttcp dport { 80, 443 } ct state new add %s ct count over %d } counter reject with tcp reset\n", src, n)
		}
	}
	b.WriteString("\t}\n}\n")
	return b.String()
}

// firewallFile is where the rules live; the unit loads them with nft -f.
const firewallFile = config.EtcDir + "/firewall.nft"

// firewallUnit returns the unit, or "" when nftables is not installed.
func firewallUnit() (string, string) {
	nft, err := exec.LookPath("nft")
	if err != nil {
		return "", ""
	}
	return nft, fmt.Sprintf(`[Unit]
Description=Entrypoint: per-IP connection limits (nftables)
PartOf=entrypoint.target
Before=entrypoint-caddy.service entrypoint-frps.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=%[1]s -f %[2]s
ExecReload=%[1]s -f %[2]s
ExecStop=%[1]s delete table inet entrypoint

[Install]
WantedBy=entrypoint.target
`, nft, firewallFile)
}
